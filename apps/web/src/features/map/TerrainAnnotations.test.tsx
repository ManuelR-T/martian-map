// @vitest-environment jsdom
import { act } from 'react';
import { createRoot } from 'react-dom/client';
import { readFileSync } from 'node:fs';
import { expect, it, vi } from 'vitest';
import type Map from 'ol/Map';
import type { DataManifest } from '@marps/data';
import { TerrainAnnotations } from './TerrainAnnotations';
import { setLanguage } from '../../i18n';
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true });
it('loads prepared data, selects through a touch list, closes and removes the layer', async () => {
 setLanguage('en');
 const manifest = JSON.parse(readFileSync('apps/web/public/data/manifest.json', 'utf8')) as DataManifest;
 const collection = JSON.parse(readFileSync('data/research/jezero-terrain-annotations.geojson', 'utf8'));
 const fetcher = vi.fn(async () => new Response(JSON.stringify(collection)));
 const addLayer = vi.fn(), removeLayer = vi.fn(), onHitsChange = vi.fn();
 const map = { addLayer, removeLayer, on: vi.fn(), un: vi.fn(), getSize: () => [1024, 768], getView: () => ({ calculateExtent: () => [-180, -90, 180, 90] }) } as unknown as Map;
 const host = document.createElement('div'); document.body.append(host);
 const root = createRoot(host);
 const render = (hits: readonly string[] | null) => <TerrainAnnotations map={map} manifest={manifest} enabled onToggle={() => {}} hits={hits} onHitsChange={onHitsChange} onClose={() => {}} fetcher={fetcher} />;
 await act(async () => { root.render(render(null)); });
 expect(fetcher).toHaveBeenCalledTimes(1);
 expect(host.querySelectorAll('[data-annotation-row]')).toHaveLength(3);
 await act(async () => { (host.querySelector('[data-annotation-row]') as HTMLButtonElement).click(); });
 expect(onHitsChange).toHaveBeenCalledWith(['ripple-field']);
 await act(async () => { root.render(render(['ripple-field'])); });
 expect(host.textContent).toContain('Repeating ridges');
 expect(host.textContent).toContain('Unknown');
 expect(host.textContent).toContain('bearing capacity');
 expect(addLayer).toHaveBeenCalledTimes(1);
 await act(async () => { root.render(render(['ripple-field', 'scarp-edge'])); });
 expect(host.textContent).toContain('Several annotations overlap');
 expect(host.querySelector('section')).toBeNull();
 await act(async () => { root.render(render(['ripple-field'])); });
 await act(async () => { Array.from(host.querySelectorAll('button')).find(button => button.textContent === 'Close inspection')!.click(); });
 expect(onHitsChange).toHaveBeenLastCalledWith(null);
 expect(document.activeElement).toBe(host.querySelector('[data-annotation-row]'));
 await act(async () => { setLanguage('fr'); });
 expect(host.textContent).toContain('Rides répétées');
 expect(fetcher).toHaveBeenCalledTimes(1);
 await act(async () => { root.unmount(); });
 expect(removeLayer).toHaveBeenCalledTimes(1);
 host.remove(); setLanguage('fr');
});
it('retries a scoped load failure and cancels a pending request when disabled', async () => {
 setLanguage('en');
 const manifest = JSON.parse(readFileSync('apps/web/public/data/manifest.json', 'utf8')) as DataManifest;
 const collection = JSON.parse(readFileSync('data/research/jezero-terrain-annotations.geojson', 'utf8'));
 const fetcher = vi.fn().mockResolvedValueOnce(new Response('', { status: 404 })).mockResolvedValueOnce(new Response(JSON.stringify(collection)));
 const host = document.createElement('div'); const root = createRoot(host);
 await act(async () => { root.render(<TerrainAnnotations map={null} manifest={manifest} enabled onToggle={() => {}} hits={null} onHitsChange={() => {}} onClose={() => {}} fetcher={fetcher} />); });
 expect(host.querySelector('[role=alert]')?.textContent).toContain('unavailable');
 await act(async () => { Array.from(host.querySelectorAll('button')).find(button => button.textContent === 'Retry annotations')!.click(); });
 expect(host.querySelectorAll('[data-annotation-row]')).toHaveLength(3);
 await act(async () => { root.unmount(); });
 let signal: AbortSignal | null | undefined;
 const pending: typeof fetch = (_input, options) => { signal = options?.signal; return new Promise(() => {}); };
 const second = createRoot(host);
 const render = (enabled: boolean) => <TerrainAnnotations map={null} manifest={manifest} enabled={enabled} onToggle={() => {}} hits={null} onHitsChange={() => {}} onClose={() => {}} fetcher={pending} />;
 await act(async () => { second.render(render(true)); });
 await act(async () => { second.render(render(false)); });
 expect(signal!.aborted).toBe(true);
 expect(host.querySelector('[role=alert]')).toBeNull();
 await act(async () => { second.unmount(); }); setLanguage('fr');
});
